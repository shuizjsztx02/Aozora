"""T-M7-05i: 产品帮助知识库与最小检索。

**范围（本卡边界）**：只回答「这个 App 怎么用」——产品功能的入口、行为与限制。
**理财知识不在范围内**（外部数据检索，本卡显式砍掉，见 `T-M7-05-P4-implementation-plan.md`
§三 05i 与 §六 05i 中间结果）：帮助里没有任何行情、产品、收益率类内容，模型
也不该把它当理财顾问用。

为什么是「本地语料 + 确定性检索」而不是向量检索或外部搜索
--------------------------------------------------------
① **语料是产品自己的事实**，不是开放语料：条目数是几十条量级，一次全表扫的
   词表匹配就够，引入 embedding / 向量库只会换来一个需要维护的索引与一个
   不可解释的排序；
② **确定性**：同一个问题永远给出同一组条目（用例可钉死）。Agent 的可解释性
   与 R-PROD-17 的抽样评估都要求这一条——排序里带随机性，问题就无从归因；
③ **不额外调用模型**：检索本身不是一次 provider 请求（与架构 §12.2 已定第 2
   项「不额外调用模型」同一取向）。

内容的唯一来源是**当前代码**（语料每条都写明用户能走到的入口），因此：

- **不写未实现的功能**，也不写「即将支持 / 规划中」这类承诺——帮助里出现一句
  产品做不到的话，模型会照着它向用户承诺，而这句承诺没有任何代码兜底；
- **不写会漂移的具体数值**（费率、限额、期限），它们由各自的实现拥有；
- 不含任何用户数据、不含 id（`HelpTopic.id` 只用于用例与文档引用，**不出现在
  检索结果里**，与读工具不回传 id 是同一口径）。

**已知限制（登记为 R-PROD-39）：** 语料是手写的、随实现漂移的静态事实——
代码改了入口而语料没改时，帮助会指向一个不存在的位置。缓解是每条都写明入口
且用例逐条核对入口文案；真正的解法（从路由表 / 文案资源生成）不在本卡范围。
"""

from __future__ import annotations

from dataclasses import dataclass

