# 语料
# ---------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class HelpTopic:
    """一条产品帮助。

    ``keywords`` 是**用户会说出口的说法**（不是功能名）：「怎么记一笔账」
    「导出」这类词才是模型要匹配的东西；``entry`` 是用户在 App 里走到的位置，
    没有入口的功能不写进语料。
    """

    id: str
    title: str
    keywords: tuple[str, ...]
    entry: str
    body: str


#: 命中的关键词权重。**只做加权求和，不做词频统计**：语料条目短、关键词是
#: 人工挑选的，词频在这里没有信息量（一条帮助里「账户」出现三次不说明它更
#: 相关）。平局按 ``id`` 排序，保证结果稳定。
_KEYWORD_WEIGHT = 3

#: 一次检索最多回给模型几条。三条＝「最相关的一条 + 两条可能相关的」：再多会
#: 把上下文撑大（每条正文上百字符），再少则容易在近义问题上漏掉正确条目。
MAX_MATCHES = 3


def search(query: str, limit: int = MAX_MATCHES) -> list[HelpTopic]:
    """按关键词命中数排序取前 ``limit`` 条（纯函数、无 IO、确定性）。

    匹配是**双向子串**：用户问「导出到哪里下载」含关键词「导出」→ 命中；用户
    只打「导出」而某条的关键词是「导出文件」→ 也命中（``q in keyword``）。中文
    没有词边界，分词器会引入一个需要维护的依赖，子串匹配在这里足够且可预测。

    一条都没命中时返回空列表（由调用方决定怎么告诉模型「这里没有」）。
    """
    raw = (query or "").strip().lower()
    if not raw:
        return []

    scored: list[tuple[int, str, HelpTopic]] = []
    for topic in TOPICS:
        score = 0
        for keyword in topic.keywords:
            word = keyword.lower()
            if word in raw or raw in word:
                score += _KEYWORD_WEIGHT
        if score:
            scored.append((score, topic.id, topic))

    # 先按分数降序，再按 id 升序——排序键里带 id 是为了**同一查询永远同一结果**
    # （Python 的 sort 稳定，但同分条目的相对顺序不该取决于语料的书写顺序）。
    scored.sort(key=lambda item: (-item[0], item[1]))
    return [topic for _, _, topic in scored[:limit]]


def topic_titles() -> list[str]:
    """全部条目的标题（语料覆盖面的清单）。

    「没命中」时把它一并回给模型：模型因此能要么按清单里最接近的一条澄清，
    要么如实说帮助里没有——**空结果本身不是答案**，一句「没找到」会让用户以为
    是整个功能不存在。
    """
    return [topic.title for topic in TOPICS]


